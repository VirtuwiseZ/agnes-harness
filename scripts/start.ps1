# scripts/start.ps1 - Multi-Environment & Multi-Instance Service Launcher
# Pure ASCII implementation to guarantee compatibility across Windows PowerShell 5.1 CP936 / UTF-8.
# Complies with official AGH architecture for AGH_HOME isolation, multi-port concurrency, and sandbox execution.

param(
    [string]$EnvMode = "",       # "isolated", "sandbox", "default", "custom"
    [int]$Port = 0,             # 0 means auto/default based on EnvMode
    [string]$WorkspaceDir = "",
    [string]$CustomHome = "",
    [switch]$NoBrowser = $false,
    [switch]$Status = $false,
    [switch]$Interactive = $false
)

$ErrorActionPreference = 'Stop'
$repoDir = Split-Path -Parent $PSScriptRoot
if (-not $repoDir) { $repoDir = (Get-Location).Path }
Set-Location $repoDir

$cliEntry = Join-Path $repoDir "packages\cli\dist\local\agnes.mjs"

# Helper function: Check if a port is currently listening
function Test-PortOccupied([int]$p) {
    try {
        $conns = Get-NetTCPConnection -LocalPort $p -State Listen -ErrorAction SilentlyContinue
        if ($conns) { return $true }
    } catch {
        $res = netstat -ano | Select-String ":$p\s+.*LISTENING"
        if ($res) { return $true }
    }
    return $false
}

# Helper function: Scan common AGH ports
function Show-AllInstances() {
    Write-Host "`n=== Active AGH Instances & Port Scanner ===" -ForegroundColor Cyan
    $portsToCheck = @(4177, 4180, 4181, 4182, 4185, 4190)
    $found = 0
    foreach ($p in $portsToCheck) {
        $listening = Test-PortOccupied $p
        if ($listening) {
            $found++
            Write-Host "  [ACTIVE] Port $p is listening -> http://127.0.0.1:$p" -ForegroundColor Green
        }
    }
    if ($found -eq 0) {
        Write-Host "  No active AGH listening ports detected on standard ranges (4177..4190)." -ForegroundColor Yellow
    }
    Write-Host "============================================`n" -ForegroundColor Cyan
}

# If user just asked for status
if ($Status) {
    Show-AllInstances
    exit 0
}

# 0. Check for instance_config.json (generated by graphical installer or previous setup)
$configPath = Join-Path $repoDir "instance_config.json"
if (-not (Test-Path $configPath) -and $WorkspaceDir) {
    $configPath = Join-Path $WorkspaceDir "instance_config.json"
}

$hasSavedConfig = $false
if ((Test-Path $configPath) -and -not $Interactive) {
    try {
        $savedJson = Get-Content $configPath -Raw -Encoding utf8 | ConvertFrom-Json
        if (-not $EnvMode -and $savedJson.envMode) {
            $EnvMode = $savedJson.envMode
            $hasSavedConfig = $true
        }
        if ((-not $Port -or $Port -eq 0) -and $savedJson.port) {
            $Port = [int]$savedJson.port
            $hasSavedConfig = $true
        }
        if (-not $CustomHome -and $savedJson.appHome) {
            $CustomHome = $savedJson.appHome
            $hasSavedConfig = $true
        }
        if ($hasSavedConfig) {
            Write-Host "[NOTE] Loaded instance configuration from: $configPath" -ForegroundColor DarkCyan
        }
    } catch {}
}

# Determine if interactive mode is needed
if (-not $EnvMode -and (-not $Port -or $Port -eq 0) -and -not $CustomHome) {
    $Interactive = $true
}

if ($Interactive) {
    Write-Host "==========================================================" -ForegroundColor Cyan
    Write-Host "   AI Physics Research Agent - Environment Selector       " -ForegroundColor Cyan
    Write-Host "==========================================================" -ForegroundColor Cyan
    Write-Host "Please select the runtime environment configuration:" -ForegroundColor Yellow
    Write-Host "  [1] Isolated Physics Environment (Default: Port 4180, Data: ~/.agh-physics)"
    Write-Host "      - Dedicated data partition, independent sessions, does not affect main AGH."
    Write-Host "  [2] Virtual Sandbox Environment  (Default: Port 4182, Data: ~/.agh-sandbox)"
    Write-Host "      - Workspace containment, forces portable Python runtime, strict isolation."
    Write-Host "  [3] Default Host Environment     (Default: Port 4177, Data: ~/.agh)"
    Write-Host "      - Connects to the system global AGH home and default workspace."
    Write-Host "  [4] Custom Instance (Multi-Tenant / Concurrent Multi-Port)"
    Write-Host "      - Specify custom port and custom AGH_HOME for concurrent instances."
    Write-Host "  [5] Scan Running Instances (View active ports & daemons)"
    Write-Host ""
    $choice = Read-Host "Enter your choice [1-5] (Default: 1)"
    if (-not $choice) { $choice = "1" }

    switch ($choice) {
        "1" { $EnvMode = "isolated" }
        "2" { $EnvMode = "sandbox" }
        "3" { $EnvMode = "default" }
        "4" { $EnvMode = "custom" }
        "5" { Show-AllInstances; exit 0 }
        default { $EnvMode = "isolated" }
    }
}

# Configure Environment Parameters based on EnvMode
switch ($EnvMode) {
    "sandbox" {
        $envTitle = "Virtual Sandbox Environment (Isolated Workspace & Portable Runtime)"
        if ($Port -eq 0) { $Port = 4182 }
        $appHome = Join-Path $env:USERPROFILE ".agh-sandbox"
        $env:PHYSICS_AGENT_FORCE_PORTABLE = "1"
    }
    "default" {
        $envTitle = "Default System Environment (Global AGH Home)"
        if ($Port -eq 0) { $Port = 4177 }
        $appHome = Join-Path $env:USERPROFILE ".agh"
    }
    "custom" {
        $envTitle = "Custom Multi-Instance Environment"
        if ($Port -eq 0) {
            $userPort = Read-Host "Enter custom port for this instance (e.g. 4185)"
            $Port = if ($userPort) { [int]$userPort } else { 4185 }
        }
        if (-not $CustomHome) {
            $userDirName = Read-Host "Enter custom home directory name under USERPROFILE (e.g. .agh-instance-$Port)"
            if (-not $userDirName) { $userDirName = ".agh-instance-$Port" }
            $appHome = Join-Path $env:USERPROFILE $userDirName
        } else {
            $appHome = $CustomHome
        }
    }
    default {
        # Isolated physics environment
        $EnvMode = "isolated"
        $envTitle = "Isolated Physics Research Environment"
        if ($Port -eq 0) { $Port = 4180 }
        $appHome = Join-Path $env:USERPROFILE ".agh-physics"
    }
}

Write-Host "`n==========================================================" -ForegroundColor Cyan
Write-Host "   AI Physics Research Agent - Starting Service           " -ForegroundColor Cyan
Write-Host "==========================================================" -ForegroundColor Cyan
Write-Host "  Target Mode : $envTitle" -ForegroundColor Green
Write-Host "  Port        : $Port" -ForegroundColor Green
Write-Host "  Data Home   : $appHome" -ForegroundColor Green

# 1. Verify build artifact
if (-not (Test-Path $cliEntry)) {
    Write-Host "[NOTE] Build artifact not detected. Running setup wizard first..." -ForegroundColor Yellow
    & (Join-Path $PSScriptRoot "setup.ps1") -SkipBuild:$false
}

# 2. Determine workspace directory
if (-not $WorkspaceDir) {
    $WorkspaceDir = Join-Path $repoDir "agh-workspace"
}
if (-not (Test-Path $WorkspaceDir)) {
    New-Item -ItemType Directory -Path $WorkspaceDir -Force | Out-Null
}

# 3. Apply isolated user data directory to environment
if (-not (Test-Path $appHome)) {
    New-Item -ItemType Directory -Path $appHome -Force | Out-Null
}
$env:AGH_HOME = $appHome

# 4. Sync skills and assets to workspace
Write-Host "`n[1/3] Syncing workspace skills and assets to: $WorkspaceDir ..." -ForegroundColor Yellow
$targetSkillsDir = Join-Path $WorkspaceDir ".agh\skills"
if (-not (Test-Path $targetSkillsDir)) {
    New-Item -ItemType Directory -Path $targetSkillsDir -Force | Out-Null
}
$sourceSkills = Join-Path $repoDir ".agh\skills"
if (Test-Path $sourceSkills) {
    Copy-Item -Path "$sourceSkills\*" -Destination $targetSkillsDir -Recurse -Force
}

$targetAgentDir = Join-Path $WorkspaceDir "physics-agent"
if (-not (Test-Path $targetAgentDir)) {
    New-Item -ItemType Directory -Path $targetAgentDir -Force | Out-Null
}
$sourceAgent = Join-Path $repoDir "physics-agent"
if (Test-Path $sourceAgent) {
    Copy-Item -Path "$sourceAgent\hooks" -Destination $targetAgentDir -Recurse -Force
    Copy-Item -Path "$sourceAgent\knowledge" -Destination $targetAgentDir -Recurse -Force
    Copy-Item -Path "$sourceAgent\plugins" -Destination $targetAgentDir -Recurse -Force
}
Write-Host "  -> Core assets synced successfully." -ForegroundColor Green

# 5. Check port and manage daemon
Write-Host "`n[2/3] Checking port $Port availability..." -ForegroundColor Yellow
$isListening = Test-PortOccupied $Port

if ($isListening) {
    Write-Host "  [NOTE] Port $Port is currently in use." -ForegroundColor Yellow
    Write-Host "         Attempting to stop existing daemon for home: $appHome ..." -ForegroundColor Yellow
    try {
        node $cliEntry daemon stop 2>$null | Out-Null
        Start-Sleep -Seconds 1
    } catch {}

    # Check again
    if (Test-PortOccupied $Port) {
        Write-Host "  [WARN] Port $Port is still in use (possibly by another application or instance)." -ForegroundColor Red
        $altPort = $Port + 1
        Write-Host "         Auto-shifting port to next available: $altPort" -ForegroundColor Yellow
        $Port = $altPort
    }
}

# 6. Start daemon service
Write-Host "`n[3/3] Starting daemon service on port $Port..." -ForegroundColor Yellow
$startResult = node $cliEntry daemon start --port $Port 2>&1
Write-Host "  -> $startResult" -ForegroundColor Green

$url = "http://127.0.0.1:$Port"
Write-Host "`n==========================================================" -ForegroundColor Cyan
Write-Host "               Service Ready                              " -ForegroundColor Cyan
Write-Host "==========================================================" -ForegroundColor Cyan
Write-Host "  Web URL     : $url" -ForegroundColor Green
Write-Host "  Mode        : $envTitle" -ForegroundColor Green
Write-Host "  Workspace   : $WorkspaceDir"
Write-Host "  AGH_HOME    : $appHome (Sessions & credentials strictly isolated)"
Write-Host "==========================================================" -ForegroundColor Cyan

# 7. Open browser
if (-not $NoBrowser) {
    Write-Host "Opening browser..." -ForegroundColor Yellow
    Start-Sleep -Milliseconds 600
    Start-Process $url
}
Write-Host "You can stop this instance anytime with: `$env:AGH_HOME='$appHome'; node $cliEntry daemon stop`n"
